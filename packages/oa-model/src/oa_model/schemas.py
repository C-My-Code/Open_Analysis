"""Generate the committed JSON Schemas from the models.

python -m oa_model.schemas --out schemas          # (re)write
python -m oa_model.schemas --out schemas --check  # exit 1 if the files differ
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

from pydantic import BaseModel

from oa_model.board import Board
from oa_model.em import EMProblem
from oa_model.physics import PhysicsOverlay
from oa_model.setup import AnalysisSetup, DesignIntent, ProjectManifest
from oa_model.xsection import CrossSection

SCHEMA_MODELS: dict[str, type[BaseModel]] = {
    "board-model.v1.json": Board,
    "oa-physics.v1.json": PhysicsOverlay,
    "oa-intent.v1.json": DesignIntent,
    "oa-setup.v1.json": AnalysisSetup,
    "oa-project.v1.json": ProjectManifest,
    "oa-xsection.v1.json": CrossSection,
    "oa-emproblem.v1.json": EMProblem,
}
# oa-result.v1.json is generated from oa_results (a separate package) and is not produced here.


def render(name: str) -> str:
    """JSON text of schema file `name`."""
    schema = SCHEMA_MODELS[name].model_json_schema()
    doc = {
        "$schema": "https://json-schema.org/draft/2020-12/schema",
        # REUSE-IgnoreStart
        "$comment": "SPDX-License-Identifier: CC-BY-4.0. Generated by 'python -m oa_model.schemas'.",
        # REUSE-IgnoreEnd
        **schema,
    }
    return json.dumps(doc, indent=2, sort_keys=True, ensure_ascii=False) + "\n"


def generate() -> dict[str, str]:
    return {name: render(name) for name in SCHEMA_MODELS}


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--out", type=Path, required=True, help="schemas directory")
    ap.add_argument("--check", action="store_true", help="compare instead of writing")
    args = ap.parse_args(argv)
    bad: list[str] = []
    for name, text in generate().items():
        target = args.out / name
        if args.check:
            current = target.read_bytes().decode("utf-8") if target.exists() else None
            if current != text:
                bad.append(name)
        else:
            args.out.mkdir(parents=True, exist_ok=True)
            with open(target, "w", encoding="utf-8", newline="\n") as fh:
                fh.write(text)
    if bad:
        print("schema files out of date: " + ", ".join(bad), file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
