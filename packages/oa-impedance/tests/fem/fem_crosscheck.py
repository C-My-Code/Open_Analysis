"""FEM vs BEM vs closed form vs exact over the fixture set; saved as a table artifact."""

from __future__ import annotations

import csv
import math
from pathlib import Path
from typing import Any

import numpy as np

from oa_impedance.errors import ImpedanceUnsupported
from oa_impedance.fem import FemParams, solve_fem
from oa_impedance.service import ImpedanceServiceImpl
from oa_model.xsection import CrossSection
from oa_results.rlgc import ImpedanceResult
from oa_results.tables import ColumnSpec, TableResult

COLUMNS = (
    ColumnSpec(name="case", dtype="str", role="id"),
    ColumnSpec(name="quantity", dtype="str"),
    ColumnSpec(name="exact", dtype="f8", unit="ohm"),
    ColumnSpec(name="closed_form", dtype="f8", unit="ohm"),
    ColumnSpec(name="bem", dtype="f8", unit="ohm"),
    ColumnSpec(name="fem", dtype="f8", unit="ohm"),
    ColumnSpec(name="fem_vs_exact_pct", dtype="f8", unit="%"),
    ColumnSpec(name="fem_vs_bem_pct", dtype="f8", unit="%"),
    ColumnSpec(name="bem_vs_exact_pct", dtype="f8", unit="%"),
    ColumnSpec(name="fem_vs_cf_pct", dtype="f8", unit="%"),
    ColumnSpec(name="fem_s", dtype="f8", unit="s"),
    ColumnSpec(name="note", dtype="str"),
)


def impedance_of(r: ImpedanceResult) -> tuple[str, float, float]:
    """(quantity, Z, eeff) of the first frequency; Zdiff for a pair, Z0 for a single line."""
    p = r.params
    if p.z_diff is not None:
        return "zdiff", float(p.z_diff.array[0]), float(np.mean(p.eps_eff_modal.array[0]))
    assert p.z0 is not None
    return "z0", float(p.z0.array[0]), float(p.eps_eff_modal.array[0, 0])


def _pct(a: float | None, b: float | None) -> float | None:
    if a is None or b is None or b == 0 or math.isnan(a) or math.isnan(b):
        return None
    return 100.0 * (a / b - 1.0)


def run_case(
    name: str,
    xs: CrossSection,
    exact: float | None,
    fem_params: FemParams | None = None,
    note: str = "",
) -> dict[str, Any]:
    import time

    svc = ImpedanceServiceImpl()
    t = time.perf_counter()
    fem = solve_fem(xs, [0.0], fem_params or FemParams(loss="none"))
    dt = time.perf_counter() - t
    q, z_fem, _ = impedance_of(fem)
    bem = svc.solve(xs, [0.0], method="bem")
    _, z_bem, _ = impedance_of(bem)
    z_cf: float | None
    try:
        _, z_cf, _ = impedance_of(svc.solve(xs, [0.0], method="closed_form"))
    except ImpedanceUnsupported:
        z_cf = None
    return {
        "case": name,
        "quantity": q,
        "exact": exact,
        "closed_form": z_cf,
        "bem": z_bem,
        "fem": z_fem,
        "fem_vs_exact_pct": _pct(z_fem, exact),
        "fem_vs_bem_pct": _pct(z_fem, z_bem),
        "bem_vs_exact_pct": _pct(z_bem, exact),
        "fem_vs_cf_pct": _pct(z_fem, z_cf),
        "fem_s": dt,
        "note": note,
    }


def to_table(rows: list[dict[str, Any]]) -> TableResult:
    inline = tuple(tuple(r[c.name] for c in COLUMNS) for r in rows)
    return TableResult(columns=COLUMNS, inline=inline, accuracy_class="reference")


def write_artifacts(rows: list[dict[str, Any]], out_dir: Path) -> None:
    out_dir.mkdir(parents=True, exist_ok=True)
    (out_dir / "table.json").write_text(
        to_table(rows).model_dump_json(indent=1) + "\n", encoding="utf-8"
    )
    names = [c.name for c in COLUMNS]
    with (out_dir / "table.csv").open("w", newline="", encoding="utf-8") as fh:
        w = csv.writer(fh)
        w.writerow(names)
        for r in rows:
            w.writerow(["" if r[n] is None else r[n] for n in names])

    def fmt(v: Any, n: str) -> str:
        if v is None:
            return "-"
        if isinstance(v, float):
            return f"{v:.3f}" if n.endswith("pct") else f"{v:.4f}" if n != "fem_s" else f"{v:.1f}"
        return str(v)

    lines = [
        "# FEM / BEM / closed-form / exact cross-check",
        "",
        "Z0 (single line) or Zdiff (pair), ohm, static. Generated by "
        "`packages/oa-impedance/tests/fem/test_crosscheck.py`.",
        "",
        "| " + " | ".join(names[:-1]) + " |",
        "|" + "---|" * (len(names) - 1),
    ]
    for r in rows:
        lines.append("| " + " | ".join(fmt(r[n], n) for n in names[:-1]) + " |")
    (out_dir / "table.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
