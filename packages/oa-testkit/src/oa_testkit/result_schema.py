"""Generate ``schemas/oa-result.v1.json`` from ``oa_results.bundle.ResultBundle``.

    python -m oa_testkit.result_schema --out schemas [--check]

``oa_model`` (L0) cannot import ``oa_results``, so its own generator skips this file. The
rendering matches ``oa_model.schemas`` (sorted keys, 2-space indent, LF).
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

from oa_results.bundle import ResultBundle

NAME = "oa-result.v1.json"


def render() -> str:
    doc = {
        "$schema": "https://json-schema.org/draft/2020-12/schema",
        "$comment": (
            "SPDX-License-Identifier: CC-BY-4.0. Generated by 'python -m oa_testkit.result_schema'."
        ),
        **ResultBundle.model_json_schema(by_alias=True),
    }
    return json.dumps(doc, indent=2, sort_keys=True, ensure_ascii=False) + "\n"


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--out", type=Path, required=True, help="schemas directory")
    ap.add_argument("--check", action="store_true", help="compare instead of writing")
    args = ap.parse_args(argv)
    text = render()
    target = args.out / NAME
    if args.check:
        if not target.exists() or target.read_bytes().decode("utf-8") != text:
            print(f"{NAME} is out of date", file=sys.stderr)
            return 1
        return 0
    args.out.mkdir(parents=True, exist_ok=True)
    target.write_text(text, encoding="utf-8", newline="\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
