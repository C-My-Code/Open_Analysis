// Generates src/api/generated/schema.d.ts from src/api/openapi.json (the WP-207 contract).
//   npm run gen:api            write the file
//   npm run gen:api -- --check fail (exit 1) if the committed file is stale
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import openapiTS, { astToString } from 'openapi-typescript';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const spec = resolve(root, 'src/api/openapi.json');
const out = resolve(root, 'src/api/generated/schema.d.ts');
const header = '// SPDX-License-Identifier: GPL-3.0-or-later\n// GENERATED by scripts/gen-api.mjs from src/api/openapi.json. Do not edit.\n';

const ast = await openapiTS(pathToFileURL(spec));
const text = (header + astToString(ast)).replace(/\r\n/g, '\n');

if (process.argv.includes('--check')) {
  let cur = '';
  try {
    cur = readFileSync(out, 'utf8').replace(/\r\n/g, '\n');
  } catch {
    /* missing */
  }
  if (cur !== text) {
    console.error('src/api/generated/schema.d.ts is stale: run `npm run gen:api` and commit the result.');
    process.exit(1);
  }
  console.log('api client is fresh');
} else {
  mkdirSync(dirname(out), { recursive: true });
  writeFileSync(out, text);
  console.log(`wrote ${out}`);
}
